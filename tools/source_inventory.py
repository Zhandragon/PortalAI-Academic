"""Index published first-party application source without importing or running it.

Usage: python tools/source_inventory.py
The inventory covers the three ApplicationSources trees. Vendored dependencies
are listed separately and are not claimed as original PortalAI code. A missing
module docstring is a navigation gap, not proof that a feature is undocumented.
"""
import ast
from collections import Counter
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SUFFIXES = {'.py','.ps1','.sh','.command','.cmd','.bat','.c','.h','.cs','.js','.mjs','.ts','.html','.css'}


def inventory():
    paths = subprocess.check_output(['git','ls-files','-z','--cached','--others','--exclude-standard',
                                     '--','ApplicationSources'], cwd=ROOT).decode().split('\0')
    records = []
    for name in sorted(set(filter(None, paths))):
        path = ROOT/name
        if path.suffix.lower() not in SUFFIXES or not path.is_file():
            continue
        parts = Path(name).parts
        if any(p.lower() in {'vendor','dependencies','node_modules','licenses'} for p in parts):
            continue
        text = path.read_text(encoding='utf-8-sig')
        row = {'path':name,'platform':parts[1],
               'component':parts[3] if len(parts)>4 else 'root',
               'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
               'lines':len(text.splitlines())}
        if path.suffix == '.py':
            try:
                tree = ast.parse(text)
                row['overview'] = (ast.get_docstring(tree) or '').split('\n')[0]
                row['symbols'] = [{'name':node.name,'line':node.lineno,'kind':type(node).__name__}
                                  for node in tree.body if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef))]
            except SyntaxError as exc:
                row['parse_error'] = f'{exc.msg} (line {exc.lineno})'
        records.append(row)
    return records


def main():
    rows = inventory()
    counts = Counter(r['platform'] for r in rows)
    missing = [r['path'] for r in rows if r['path'].endswith('.py') and not r.get('overview')]
    report = {'scope':'Tracked and new non-vendored code under ApplicationSources only; not a live-drive or binary-release audit.',
              'files_per_platform':dict(counts),'python_files_without_module_overview':missing,
              'files':rows}
    docs = ROOT/'Documentation'
    (docs/'SOURCE-INVENTORY.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    lines = ['# Application module index','',
             'Generated by [source_inventory.py](../tools/source_inventory.py). '+
             'Windows entry points are listed below; corresponding Linux and Mac files are in '+
             '[the complete inventory](SOURCE-INVENTORY.json), with hashes and top-level symbol locations.', '',
             'An overview below is taken verbatim from the module docstring. “No module overview” '+
             'means there is no top-level Python docstring; inline comments, tests and Help may still document it. '+
             'This index does not certify exhaustive documentation or prove that disconnected installations match GitHub.', '']
    components = sorted({r['component'] for r in rows if r['platform']=='Windows'})
    for component in components:
        lines += ['## '+component,'','| Source | Overview |','| --- | --- |']
        for row in rows:
            if row['platform'] != 'Windows' or row['component'] != component:
                continue
            label = row['path'].split('/PortalAI/',1)[-1]
            overview = row.get('overview') or ('No module overview; see source and symbol inventory.' if label.endswith('.py') else 'Source script; inspect its comments and entry points.')
            lines.append('| ['+label+'](../'+row['path'].replace(' ','%20')+') | '+overview.replace('|','\\|')+' |')
        lines.append('')
    (docs/'MODULE-INDEX.md').write_text('\n'.join(lines).rstrip()+'\n',encoding='utf-8')
    print(json.dumps({'files_per_platform':dict(counts),'python_files_without_overview':len(missing)},indent=2))


if __name__ == '__main__':
    main()
